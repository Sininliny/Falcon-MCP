"""Live MIDI capture from the standalone bridge, performance profiles and touch calibration."""

from __future__ import annotations

import asyncio
import re
from typing import Annotated, Any, Literal

from pydantic import Field

from .bridge import atomic_json
from .midi_capture import (
    load_performance,
    performance_path,
    profile,
    raw_from_capture,
    raw_to_events,
    save_performance,
    touch_curve,
)

READ = {"readOnlyHint": True, "destructiveHint": False, "idempotentHint": True, "openWorldHint": False}
WRITE = {"readOnlyHint": False, "destructiveHint": False, "idempotentHint": False, "openWorldHint": False}
Name = Annotated[str, Field(pattern=r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$")]
Velocity = Annotated[int, Field(ge=1, le=127)]
PAGE = 500
CAPTURE_LIMITATIONS = (
    "Records what reaches the MCP Master Script Processor of the open Falcon: the player's keyboard, pedal and "
    "wheels as the standalone or host delivers them (after any host-side MIDI filtering). Timestamps are Falcon "
    "engine time (milliseconds, block-quantized), not the keyboard's own clock. Events generated by scripts "
    "downstream of the Master are not seen. The capture lives in memory until saved; a bridge reload or "
    "closing Falcon loses it.")


def _declare_scopes():
    try:  # Result-scope profiles; absent in trees without result_scope.py.
        from .result_scope import CODES, declare
    except ImportError:
        return
    CODES.update(live_midi_capture="MIDI that reached the open instance's Master script was recorded.",
                 velocity_statistics="Velocity, pedal and controller statistics were computed from the events.")
    declare("falcon_midi_capture", "open_instance", ["live_midi_capture"],
            ["audible_effect", "part_routing", "perceptual_quality"], "midi",
            note="Records incoming MIDI only; no sound is produced or recorded.")
    declare("falcon_performance_profile", "managed_files", ["velocity_statistics"],
            ["audible_effect", "perceptual_quality"],
            note="A touch curve is a starting point for the instrument's velocity response, not a verified setting.")


def register_capture(mcp, config, audit, bridge):
    _declare_scopes()
    capture_root = config.audio_root / "captures"

    @mcp.tool(annotations=WRITE)
    async def falcon_midi_capture(
        action: Literal["start", "stop", "status", "save"] = "status",
        name: Name | None = None,
        max_seconds: Annotated[int, Field(ge=1, le=3600)] = 600,
    ) -> dict[str, Any]:
        """Record the user's live playing in the open Falcon (standalone or DAW) for offline replay and analysis.

        start clears and arms an in-memory capture in the MCP Master bridge (auto-stops after max_seconds);
        ask the user to play, then stop; save writes <audio>/captures/<name>.performance.json and .mid.
        Replay the saved file with falcon_native_perform(performance_path=...) and calibrate velocity response
        with falcon_performance_profile. Captures note on/off with velocity, all CCs (CC64 pedal incl. half-pedal
        values, CC1), pitch bend and pressure. The bridge refuses to reload while a capture is armed.
        An older bridge runtime answers 'Unsupported operation'; redeploy it with falcon_setup.
        """
        if action == "start":
            audit.event("midi_capture_start", max_seconds=max_seconds)
            status = await bridge.request("midi_capture", {"action": "start", "max_seconds": max_seconds})
            return {**_status(status), "next": "Ask the user to play now; then falcon_midi_capture(action='stop')",
                    "limitations": CAPTURE_LIMITATIONS}
        if action in ("stop", "status"):
            status = await bridge.request("midi_capture", {"action": action})
            out = _status(status)
            if action == "stop":
                out["next"] = "falcon_midi_capture(action='save', name=...)"
            return out
        if name is None:
            raise ValueError("save requires a name")
        first = await bridge.request("midi_capture", {"action": "stop"})
        generation, rows, offset = first.get("generation"), [], 0
        while True:
            page = await bridge.request("midi_capture", {"action": "read", "generation": generation,
                                                         "offset": offset, "limit": PAGE})
            events = page.get("events") or []
            rows.extend(events if isinstance(events, list) else [])
            offset = page.get("next_offset", offset + len(events))
            if not page.get("has_more") or not events:
                break
        if not rows:
            raise ValueError("The capture holds no MIDI events; check that the keyboard reaches the standalone "
                             "and that falcon_midi_capture(action='start') ran before playing")
        raw = raw_from_capture(rows)
        events, info = await asyncio.to_thread(raw_to_events, raw, first.get("elapsed_ms", 0) / 1000)
        capture_root.mkdir(parents=True, exist_ok=True)
        base = performance_path(config.audio_root, f"captures/{name}", must_exist=False)
        if base.with_suffix(".performance.json").exists():
            raise ValueError("A capture with this name exists; choose a new name")
        meta = {"captured_messages": len(rows), "dropped_messages": first.get("dropped", 0),
                "generation": generation, **info}
        paths = await asyncio.to_thread(save_performance, events, base, meta)
        stats = await asyncio.to_thread(profile, events)
        audit.event("midi_capture_saved", name=name, messages=len(rows))
        return {**paths, "messages": len(rows), "dropped": first.get("dropped", 0), "unclosed_notes":
                info["unclosed_notes"], "profile": _brief(stats),
                "next": "falcon_performance_profile(path) for the touch curve; "
                        "falcon_native_perform(performance_path=...) to replay offline (60 s windows)",
                "limitations": CAPTURE_LIMITATIONS}

    @mcp.tool(annotations=READ)
    async def falcon_performance_profile(
        path: str,
        touch_low: Velocity = 16, touch_high: Velocity = 127,
        touch_median: Velocity | None = None,
    ) -> dict[str, Any]:
        """Profile a recorded performance (capture .performance.json or any .mid under the audio root) and
        derive a touch (velocity) curve from the player's real velocity distribution.

        Reports velocity percentiles, an ASCII histogram, per-register medians, note density, polyphony,
        sustain-pedal use and controller ranges. The touch curve maps the player's p2..p98 velocities onto
        touch_low..touch_high with the median at touch_median (default: midpoint). Apply it to the instrument's
        velocity/Touch control (find it with falcon_param_search or the Program's script UI), or audition it
        offline with falcon_native_perform(performance_path=..., touch_curve=...). Statistics only; whether the
        result feels right is for the player to judge.
        """
        target = performance_path(config.audio_root, path)
        events, info = await asyncio.to_thread(load_performance, target)
        stats = await asyncio.to_thread(profile, events)
        velocities = [int(e["velocity"]) for e in events if e["type"] == "note"]
        if touch_high - touch_low < 8:
            raise ValueError("touch_high must exceed touch_low by at least 8")
        curve = touch_curve(velocities, touch_low, touch_high, touch_median)
        saved = target.with_name(re.sub(r"(\.performance)?\.json$|\.midi?$", "", target.name) + ".profile.json")
        await asyncio.to_thread(atomic_json, saved, {"source": info, "profile": stats, "touch_curve": curve})
        return {"path": str(target), "source": info.get("source"), "profile": stats, "touch_curve": curve,
                "saved": str(saved)}

    def _status(status: dict) -> dict:
        keys = ("armed", "count", "dropped", "limit", "elapsed_ms", "expired", "hooked", "error", "generation")
        return {k: status.get(k) for k in keys if status.get(k) is not None}

    def _brief(stats: dict) -> dict:
        return {k: stats[k] for k in ("notes", "seconds", "range", "max_held_keys", "sustain_pedal")} | {
            "velocity": {k: v for k, v in stats["velocity"].items() if k != "histogram"}}
