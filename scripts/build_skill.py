"""Package the agent skill: generated reference index plus an optional upload ZIP.

The tracked skill folder never contains generated content, so parallel pull requests that add
references or tools do not edit the same lines. Each ``references/*.md`` file declares when to read
it in a ``read_when:`` front-matter line; this script copies the skill to ``--out`` and replaces the
``reference-index`` marker in SKILL.md with one bullet per reference, sorted by file name.

    python scripts/build_skill.py                                   # build .runtime/skill-build
    python scripts/build_skill.py --zip .runtime/falcon-instrument-workflow.zip
    python scripts/build_skill.py --check                           # validate only, write nothing
"""

from __future__ import annotations

import argparse
import shutil
import sys
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SKILL_NAME = "falcon-instrument-workflow"
SOURCE = REPO / "skills" / SKILL_NAME
MARKER = "<!-- reference-index: generated by scripts/build_skill.py; do not edit by hand -->"


def read_when(path: Path) -> str:
    """Return the ``read_when`` value from a reference file's front matter."""
    lines = path.read_text("utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path.name}: must start with front matter containing read_when:")
    for line in lines[1:]:
        if line.strip() == "---":
            break
        key, _, value = line.partition(":")
        if key.strip() == "read_when" and value.strip():
            return value.strip()
    raise ValueError(f"{path.name}: front matter has no read_when: line")


def title(path: Path) -> str:
    for line in path.read_text("utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip().strip("`")
    return path.stem.replace("-", " ")


def reference_index(source: Path = SOURCE) -> str:
    bullets = []
    for path in sorted((source / "references").glob("*.md")):
        bullets.append(f"- [{title(path)}](references/{path.name}): {read_when(path)}")
    return "\n".join(bullets)


def render_skill(source: Path = SOURCE) -> str:
    text = (source / "SKILL.md").read_text("utf-8")
    if text.count(MARKER) != 1:
        raise ValueError("SKILL.md must contain the reference-index marker exactly once")
    return text.replace(MARKER, reference_index(source))


def build(out: Path, source: Path = SOURCE) -> Path:
    """Copy the skill to ``out/<name>`` with the generated SKILL.md; return that folder."""
    skill = render_skill(source)
    target = out / source.name
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(source, target, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"))
    (target / "SKILL.md").write_text(skill, "utf-8", newline="")
    return target


def write_zip(folder: Path, archive: Path) -> None:
    """Zip ``folder`` with forward-slash names under a single ``<name>/`` parent."""
    archive.parent.mkdir(parents=True, exist_ok=True)
    if archive.exists():
        archive.unlink()
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(p for p in folder.rglob("*") if p.is_file()):
            zf.write(path, (Path(folder.name) / path.relative_to(folder)).as_posix())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=REPO / ".runtime" / "skill-build",
                        help="folder that receives the built skill folder (default .runtime/skill-build)")
    parser.add_argument("--zip", type=Path, help="also write an upload ZIP for Claude Desktop here")
    parser.add_argument("--check", action="store_true", help="validate front matter and marker only")
    args = parser.parse_args(argv)
    try:
        if args.check:
            render_skill()
            print("skill ok")
            return 0
        folder = build(args.out)
        print(f"built {folder}")
        if args.zip:
            write_zip(folder, args.zip)
            print(f"wrote {args.zip}")
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
